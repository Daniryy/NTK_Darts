const norm = s => String(s == null ? '' : s).trim().toLowerCase().replace(/ё/g, 'е').replace(/^г\.\s*/, '').replace(/\s+/g, ' ');
// поиск: слова «область», «обл.», «республика» в запросе не мешают найти область
const STOP = new Set(['область', 'обл', 'обл.', 'республика', 'респ', 'респ.']);
const normQ = s => norm(s).split(' ').filter(w => !STOP.has(w)).join(' ');
const BY_CITY = new Map();
REGIONS.forEach(([r, cs]) => cs.forEach(c => { if (!BY_CITY.has(norm(c))) BY_CITY.set(norm(c), r); }));

const regionOf = city => BY_CITY.get(norm(city)) || null;
// города области — в нижнем регистре, «ё» как «е»: для сравнения с norm(city) в SQL
const citiesOf = region => { const x = REGIONS.find(r => r[0] === region); return x ? x[1].map(norm) : []; };
// области, в названии которых есть запрос (от 3 букв)
function findRegions(q) {
  const s = normQ(q);
  if (s.length < 3) return [];
  return REGIONS.filter(([r]) => norm(r).includes(s)).map(r => r[0]);
}
// SQL-выражение города в том же виде, что norm()
const citySql = col => `regexp_replace(replace(lower(btrim(${col})), 'ё', 'е'), '^г\\.\\s*', '')`;

module.exports = { REGIONS, regionOf, citiesOf, findRegions, norm, citySql };
